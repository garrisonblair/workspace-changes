"""Generate media/codicons.js from the official vscode-codicons SVG sources.
Usage: python3 scripts/build-codicons.py <path-to-vscode-codicons-checkout>"""
import json, pathlib, re, sys
NAMES = ['check', 'add', 'remove', 'discard', 'go-to-file', 'chevron-right', 'chevron-down', 'git-branch',
         'sync', 'cloud-upload', 'ellipsis', 'refresh', 'arrow-up', 'arrow-down', 'git-pull-request-create']
src = pathlib.Path(sys.argv[1]) / 'src' / 'icons'
out = {}
for n in NAMES:
    svg = (src / f'{n}.svg').read_text().strip()
    svg = re.sub(r'\s(width|height)="16"', '', svg, count=2)
    svg = svg.replace('<svg ', f'<svg class="codicon codicon-{n}" aria-hidden="true" ', 1)
    out[n] = svg
root = pathlib.Path(__file__).resolve().parent.parent
(root / 'media' / 'codicons.js').write_text(
    '// Generated by scripts/build-codicons.py from microsoft/vscode-codicons (CC BY 4.0). Do not edit.\n'
    'window.CODICONS = ' + json.dumps(out, indent=1) + ';\n')
print(len(out), 'icons')
