def icon_fixture(theme, base):
    paths = sorted({f'{r}/{p}' for r, fl in FILES.items() for _, p, _, _ in fl})
    out = subprocess.run(['node', str(ROOT / 'test' / 'icon_fixture.js'), theme, base, *paths], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)

def make_model(classes):
    def repo(root, label, branch, *, is_default=False, ahead=0, behind=0, unpublished=False, primary=None, pr=False):
        groups = []
        for key, lbl in (('index', 'Staged Changes'), ('working', 'Changes')):
            fl = [f for f in FILES.get(root, []) if f[0] == key]
            if fl:
                groups.append({'key': key, 'label': lbl, 'count': len(fl), 'files': [{
                    'uri': f'file://{root}/{p}', 'name': p.split('/')[-1], 'dir': '/'.join(p.split('/')[:-1]), 'letter': L,
                    'statusText': c, 'cls': 'untracked' if L == 'U' else c, 'untracked': L == 'U',
                    'iconClasses': classes[f'{root}/{p}']} for _, p, L, c in fl]})
        changes = sum(g['count'] for g in groups)
        return {'root': root, 'label': label, 'branch': branch, 'detached': False, 'isDefault': is_default,
                'defaultBranch': 'main', 'defaultDetected': True, 'ahead': ahead, 'behind': behind,
                'unpublished': unpublished, 'hasUpstream': not unpublished, 'hasRemote': True, 'canCreatePr': pr,
                'changes': changes, 'staged': sum(g['count'] for g in groups if g['key'] == 'index'), 'inputValue': '',
                'primary': primary or {'kind': 'commit', 'label': 'Commit', 'enabled': changes > 0}, 'groups': groups}
    return {'mac': True, 'total': 23, 'showAll': False, 'textFilter': '', 'fileIcons': True, 'repos': [
        repo('/ws/api', 'api', 'main', is_default=True),
        repo('/ws/billing', 'billing', 'fix/invoice-rounding', unpublished=True, pr=True,
             primary={'kind': 'publish', 'label': 'Publish Branch', 'enabled': True}),
        repo('/ws/front', 'front', 'feat/new-header', ahead=2, behind=1, pr=True),
        repo('/ws/infra', 'infra', 'main', is_default=True, behind=3, primary={'kind': 'sync', 'label': 'Sync Changes 3↓', 'enabled': True}),
    ]}

def harness(theme_css, body_class):
    vars_ = ';'.join(f'{k}:{v}' for k, v in DARK_MODERN.items())
    return f"""<!DOCTYPE html><html><head><meta charset="utf-8">
<link rel="stylesheet" href="/media/view.css">
<style>:root{{{vars_}}} body{{background:var(--vscode-sideBar-background);}}</style>
<style id="file-icon-theme">{theme_css}</style>
<script>
  window.__posted = []; window.__state = undefined; window.__menus = [];
  // same logic as VS Code's webview host (src/vs/workbench/contrib/webview/browser/pre/index.html)
  window.addEventListener('contextmenu', e => {{
    if (e.defaultPrevented) return;
    e.preventDefault();
    let context = {{}}; let el = e.target;
    while (true) {{ if (!el) break; el = el.closest('[data-vscode-context]'); if (!el) break;
      context = {{ ...JSON.parse(el.dataset.vscodeContext), ...context }}; el = el.parentElement; }}
    window.__menus.push({{ clientX: e.clientX, clientY: e.clientY, context, postedBefore: window.__posted.length }});
  }});
  window.acquireVsCodeApi = () => ({{ postMessage: (m) => window.__posted.push(m), getState: () => window.__state, setState: (s) => {{ window.__state = s; }} }});
</script></head>
<body class="{body_class}"><div id="app" class="loading">Loading repositories…</div>
<script src="/media/codicons.js"></script><script src="/media/view.js"></script></body></html>"""

